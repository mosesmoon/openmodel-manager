const dicts: Record<Lang, Record<Key, string>> = { "zh-TW": zh, en };

export type T = (k: Key) => string;

const Ctx = createContext<{ lang: Lang; t: T }>({ lang: "zh-TW", t: (k) => zh[k] });

export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  const d = dicts[lang] ?? zh;
  return <Ctx.Provider value={{ lang, t: (k) => d[k] ?? k }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  return useContext(Ctx);
}
